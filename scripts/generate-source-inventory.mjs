import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'docs/source-map/INVENTORY.md');
const roots = ['packages', 'packages-private', 'scripts'];
const extensions = new Set(['.ts','.tsx','.js','.jsx','.mjs','.cjs','.vue','.vune','.scss','.sass','.css','.html','.json','.json5','.yml','.yaml','.sh']);
const args = process.argv.slice(2);
const i = args.indexOf('--upstream');
const upstream = i >= 0 && args[i + 1] ? path.resolve(args[i + 1]) : null;

async function exists(p){ try { await stat(p); return true; } catch { return false; } }
async function walk(dir){
  const out=[];
  for(const e of await readdir(dir,{withFileTypes:true})){
    if(e.name==='node_modules'||e.name==='.git') continue;
    const f=path.join(dir,e.name);
    if(e.isDirectory()) out.push(...await walk(f));
    else if(extensions.has(path.extname(e.name))||e.name.endsWith('.vune')) out.push(f);
  }
  return out;
}
async function digest(p){ return createHash('sha256').update(await readFile(p)).digest('hex'); }
function area(rel){
  const p=rel.split('/');
  if(p[0]==='scripts') return 'tooling';
  if(p[0]==='packages-private') return 'private package';
  if(p[0]!=='packages') return p[0];
  return ({backend:'backend',frontend:'frontend',sw:'service worker','misskey-js':'client SDK','frontend-shared':'frontend shared','frontend-embed':'embed frontend','frontend-builder':'frontend build',shared:'shared',i18n:'i18n',modules:'linked module'})[p[1]] ?? p[1] ?? 'packages';
}
function label(rel){ return path.basename(rel,path.extname(rel)).replace(/[-_.]+/g,' ').replace(/([a-z0-9])([A-Z])/g,'$1 $2'); }
function purpose(rel){
  const l=label(rel);
  if(/\/migration\//.test(rel)) return `Database migration ${l}; schema history.`;
  if(/\.(test|spec)\./.test(rel)) return `Tests for ${l}.`;
  if(/\.stories\./.test(rel)) return `Storybook scenarios for ${l}.`;
  if(/\/server\/api\/endpoints\//.test(rel)) return `Backend API endpoint for ${rel.split('/endpoints/')[1].replace(/\.ts$/,'')}.`;
  if(/\/core\/entities\//.test(rel)) return `Entity packing and API serialization for ${l}.`;
  if(/\/core\/activitypub\//.test(rel)) return `ActivityPub processing for ${l}.`;
  if(/\/queue\/processors\//.test(rel)) return `Background queue processor for ${l}.`;
  if(/\/boot\//.test(rel)) return `Backend startup or shutdown path for ${l}.`;
  if(/\/misc\//.test(rel)&&rel.includes('/backend/')) return `Backend utility for ${l}.`;
  if(rel.endsWith('.vune')) return `Vune view or renderer for ${l}.`;
  if(rel.endsWith('.vue')) return `Vue component/page for ${l}; may host Vune during migration.`;
  if(/\/src\/vune\//.test(rel)) return `Vune integration/runtime support for ${l}.`;
  if(rel.startsWith('scripts/')) return `Repository tooling for ${l}.`;
  if(/packages\/sw\/src\//.test(rel)) return `Service Worker source for ${l}.`;
  if(/packages\/misskey-js\//.test(rel)) return `Misskey JavaScript client SDK source for ${l}.`;
  return `Source or configuration for ${l}.`;
}

const files=[];
for(const r of roots){ const d=path.join(root,r); if(await exists(d)) files.push(...await walk(d)); }
files.sort((a,b)=>a.localeCompare(b));
const rows=[];
for(const file of files){
  const rel=path.relative(root,file).split(path.sep).join('/');
  let delta='current';
  if(upstream){ const u=path.join(upstream,rel); delta=!await exists(u)?'added':await digest(file)===await digest(u)?'same':'modified'; }
  rows.push(`| \`${rel}\` | ${area(rel)} | ${delta} | ${purpose(rel)} |`);
}
await mkdir(path.dirname(output),{recursive:true});
await writeFile(output,`# Source inventory\n\nGenerated by \`scripts/generate-source-inventory.mjs\`.\n\nSource files indexed: ${rows.length}.\n\n| Path | Area | Delta | Purpose |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n`);
console.log(`Wrote ${output} with ${rows.length} source rows.`);